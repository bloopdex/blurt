#!/usr/bin/env node
// Collects the installers from a `tauri build` into dist/ under stable names, checks that each one
// really is an installer of the expected format, and writes SHA256SUMS.txt plus site/release.js.
//
//   node scripts/package.mjs                       # after `pnpm tauri build`
//   node scripts/package.mjs --target aarch64-apple-darwin
//
// Stable names (no version) let the website link to .../releases/latest/download/<name>.
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const targetArg = process.argv.indexOf("--target");
const target = targetArg > 0 ? process.argv[targetArg + 1] : null;
const version = JSON.parse(readFileSync(join(root, "src-tauri/tauri.conf.json"), "utf8")).version;
const bundleDir = join(root, "src-tauri/target", target ?? "", "release/bundle");
const dist = join(root, "dist");

/** Magic-number checks: a renamed or truncated file must not ship as an installer. */
const formats = {
  nsis(buf) {
    if (buf.readUInt16LE(0) !== 0x5a4d) return "missing MZ header";
    const pe = buf.readUInt32LE(0x3c);
    if (buf.toString("latin1", pe, pe + 4) !== "PE\0\0") return "missing PE signature";
    // NSIS appends its data block, tagged "NullsoftInst", after the PE image.
    if (!buf.includes(Buffer.from("NullsoftInst", "latin1"))) return "not an NSIS installer";
    return null;
  },
  msi(buf) {
    // MSI is an OLE compound document.
    return buf.subarray(0, 8).equals(Buffer.from([0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1])) ? null : "not an OLE/MSI file";
  },
  dmg(buf) {
    // UDIF images end with a 512-byte "koly" trailer.
    return buf.toString("latin1", buf.length - 512, buf.length - 508) === "koly" ? null : "missing UDIF trailer";
  },
};

const arch = (target ?? process.arch).includes("aarch64") || (!target && process.arch === "arm64") ? "arm64" : "x64";
const wanted = [
  { dir: "nsis", match: (f) => f.endsWith("-setup.exe"), name: "Blurt-Setup.exe", format: "nsis", platform: "windows" },
  { dir: "msi", match: (f) => f.endsWith(".msi"), name: "Blurt-Setup.msi", format: "msi", platform: "windows" },
  { dir: "dmg", match: (f) => f.endsWith(".dmg"), name: `Blurt-macOS-${arch}.dmg`, format: "dmg", platform: "macos" },
];

mkdirSync(dist, { recursive: true });
const produced = [];
for (const w of wanted) {
  const dir = join(bundleDir, w.dir);
  if (!existsSync(dir)) continue;
  const file = readdirSync(dir).find((f) => w.match(f) && f.includes(version));
  if (!file) continue;
  const src = join(dir, file);
  const buf = readFileSync(src);
  const problem = formats[w.format](buf);
  if (problem) {
    console.error(`✗ ${file}: ${problem}`);
    process.exit(1);
  }
  copyFileSync(src, join(dist, w.name));
  const sha256 = createHash("sha256").update(buf).digest("hex");
  produced.push({ name: w.name, platform: w.platform, format: w.format, size: statSync(src).size, sha256 });
  console.log(`✓ ${w.name}  ${(buf.length / 1048576).toFixed(1)} MB  ${w.format.toUpperCase()} verified  sha256 ${sha256.slice(0, 16)}…`);
}
if (!produced.length) {
  console.error(`No ${version} installers found in ${bundleDir}. Run \`pnpm tauri build\` first.`);
  process.exit(1);
}

// Merge with checksums already in dist/ (e.g. from other platforms) and rewrite.
const sumsPath = join(dist, "SHA256SUMS.txt");
const sums = new Map(
  existsSync(sumsPath)
    ? readFileSync(sumsPath, "utf8").split("\n").filter(Boolean).map((l) => [l.split(/\s+/)[1], l.split(/\s+/)[0]])
    : [],
);
for (const p of produced) sums.set(p.name, p.sha256);
writeFileSync(sumsPath, [...sums].map(([n, h]) => `${h}  ${n}`).join("\n") + "\n");

// Release notes for this version from CHANGELOG.md, for the download page.
const changelog = readFileSync(join(root, "CHANGELOG.md"), "utf8");
const section = changelog.split(/^## /m).find((s) => s.startsWith(`[${version}]`)) ?? "";
const notes = section.split("\n").slice(1).join("\n").trim();
const releasePath = join(root, "site/release.js");
const prev = existsSync(releasePath) ? JSON.parse(readFileSync(releasePath, "utf8").replace(/^[^{]*/, "").replace(/;\s*$/, "")) : {};
const files = { ...(prev.version === version ? prev.files : {}) };
for (const p of produced) files[p.name] = { platform: p.platform, size: p.size, sha256: p.sha256 };
const release = { version, date: new Date().toISOString().slice(0, 10), notes, files };
writeFileSync(releasePath, `// Generated by scripts/package.mjs — do not edit.\nwindow.BLURT_RELEASE = ${JSON.stringify(release, null, 2)};\n`);
console.log(`Wrote dist/SHA256SUMS.txt and site/release.js for v${version}.`);
